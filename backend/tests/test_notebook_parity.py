import pytest
import pandas as pd
import numpy as np

from backend.services.csv_loader import load_csv
from backend.services.csv_validator import validate_or_raise
from backend.services.data_preprocessor import preprocess_dataframe
from backend.services.weekly_aggregator import aggregate_weekly_demand


def test_notebook_parity_against_reference_dataset(sales_data_csv_path, weekly_demand_csv_path):
    """
    CRITICAL PARITY TEST:
    Execute the refactored backend pipeline on sales_data.csv and compare the output
    directly against weekly_product_demand.csv generated by Notebook 01.
    """
    # 1. Run backend pipeline
    raw_df = load_csv(sales_data_csv_path)
    validate_or_raise(raw_df)
    processed_df = preprocess_dataframe(raw_df)
    backend_weekly_df = aggregate_weekly_demand(processed_df)

    # 2. Load Notebook 01 reference output
    reference_weekly_df = pd.read_csv(weekly_demand_csv_path)
    reference_weekly_df["Week_Ending"] = pd.to_datetime(reference_weekly_df["Week_Ending"])

    # 3. Assert Dimensions & Metadata Parity
    assert len(backend_weekly_df) == 2200, f"Expected 2200 rows, got {len(backend_weekly_df)}"
    assert len(backend_weekly_df) == len(reference_weekly_df), "Row counts do not match!"
    assert list(backend_weekly_df.columns) == ["Product ID", "Week_Ending", "Weekly_Demand"]
    assert list(reference_weekly_df.columns) == ["Product ID", "Week_Ending", "Weekly_Demand"]

    # 4. Assert Unique Counts
    assert backend_weekly_df["Product ID"].nunique() == 20
    assert backend_weekly_df["Week_Ending"].nunique() == 110
    assert reference_weekly_df["Product ID"].nunique() == 20
    assert reference_weekly_df["Week_Ending"].nunique() == 110

    # 5. Assert Date Boundaries
    assert backend_weekly_df["Week_Ending"].min() == pd.Timestamp("2022-01-02")
    assert backend_weekly_df["Week_Ending"].max() == pd.Timestamp("2024-02-04")
    assert reference_weekly_df["Week_Ending"].min() == pd.Timestamp("2022-01-02")
    assert reference_weekly_df["Week_Ending"].max() == pd.Timestamp("2024-02-04")

    # 6. Assert Total Sum of Demand
    total_raw_demand = int(raw_df["Demand"].sum())
    total_backend_weekly = int(backend_weekly_df["Weekly_Demand"].sum())
    total_ref_weekly = int(reference_weekly_df["Weekly_Demand"].sum())

    assert total_raw_demand == 7928104, f"Unexpected raw demand: {total_raw_demand}"
    assert total_backend_weekly == 7928104, f"Backend weekly sum mismatch: {total_backend_weekly}"
    assert total_ref_weekly == 7928104, f"Reference weekly sum mismatch: {total_ref_weekly}"

    # 7. Exact Row-by-Row Equality
    backend_sorted = backend_weekly_df.sort_values(by=["Product ID", "Week_Ending"]).reset_index(drop=True)
    ref_sorted = reference_weekly_df.sort_values(by=["Product ID", "Week_Ending"]).reset_index(drop=True)

    pd.testing.assert_frame_equal(backend_sorted, ref_sorted, check_dtype=True)
